from __future__ import annotations

import hashlib
import logging
import os
from dataclasses import dataclass
from pathlib import Path
from typing import Literal

import yaml
from fastapi import Header, HTTPException

Tier = Literal["read", "actuate", "commission"]


@dataclass(frozen=True)
class AuthContext:
    #: The bearer entry's `caller` name, or None when the entry declares none.
    #: Names a CREDENTIAL, not a person.
    caller_id: str | None
    tier: Tier
    api_key: str

    @property
    def api_key_fingerprint(self) -> str:
        return hashlib.sha256(self.api_key.encode()).hexdigest()[:12]


@dataclass(frozen=True)
class _BearerEntry:
    token: str
    tier: Tier
    #: WHICH CREDENTIAL, NEVER WHICH PERSON. `caller_id` is the name the
    #: operator wrote next to a token in bearers.yaml ("craig-iphone",
    #: "readonly-probe"). It says which key was presented, not who was holding
    #: the phone; a custody record that could say more does not exist yet.
    #: Optional: a bearers.yaml written before `castor up` generated the field
    #: still loads, with caller_id None.
    caller_id: str | None = None
    #: SUPERVISOR marks the HEARTBEAT credential, and nothing else is one. SF-002
    #: asks whether the person who can stop the robot still has a working link
    #: to it, so the heartbeat must come from that person's device, never from
    #: the agent the heartbeat supervises. A supervisor holds the read tier: on
    #: /v1/invoke it can stop the robot and read its state and can never move
    #: it. None for every other entry.
    role: str | None = None


#: The one role a bearer entry may declare (`role: supervisor` in bearers.yaml).
SUPERVISOR = "supervisor"

#: Shorter tokens load, with a `weak_bearer_token` warning. Refusing them would
#: break hand-written files that work today; robot-md's installer refuses them.
MIN_TOKEN_CHARS = 16


class BearerStore:
    def __init__(self, entries: list[_BearerEntry]) -> None:
        self._by_token = {e.token: e for e in entries}

    @classmethod
    def from_yaml(cls, path: Path) -> BearerStore:
        data = yaml.safe_load(path.read_text())
        # Two accepted shapes:
        #   1. Legacy: top-level list of bearer entries.
        #   2. New (v0.5.0a1+): top-level dict with `bearers:` and optional
        #      `actuator:` keys.
        if data is None:
            data = []
        if isinstance(data, dict):
            rows = data.get("bearers") or []
        elif isinstance(data, list):
            rows = data
        else:
            raise ValueError(
                f"{path}: top-level must be a list (legacy) or a dict with 'bearers' "
                f"key (v0.5.0a1+); got {type(data).__name__}"
            )
        entries = []
        for row in rows:
            # `caller` is OPTIONAL. It is generated by `castor up` and every
            # live bearers.yaml carries it, but a hand-written or pre-0.5 file
            # must still start the gateway rather than crash it at boot; the
            # receipt then records caller: null, which is honest.
            role = row.get("role")
            if role is None:
                tier = row["tier"]
            elif role == SUPERVISOR:
                # A supervisor that could also move the robot would let the
                # thing being supervised keep its own heartbeat alive.
                tier = row.get("tier", "read")
                if tier != "read":
                    raise ValueError(
                        f"{path}: supervisor credential {row.get('caller')!r} has tier "
                        f"{tier!r}. A supervisor sends heartbeats and must not be able "
                        f"to move the robot: give it tier read, or no tier."
                    )
            else:
                raise ValueError(
                    f"{path}: unknown role {role!r} for caller {row.get('caller')!r}; "
                    f"the only role is {SUPERVISOR!r}"
                )
            entries.append(_BearerEntry(
                token=row["token"], tier=tier, caller_id=row.get("caller"), role=role,
            ))
        if not entries:
            raise ValueError(f"{path} has no bearer entries")
        for e in entries:
            if e.tier not in ("read", "actuate", "commission"):
                raise ValueError(f"invalid tier {e.tier!r} for caller {e.caller_id}")
            # A placeholder is a public string. robot-md's installer shipped
            # `REPLACE-WITH-MINTED-TOKEN`, and a file that kept it (with a tier
            # added by hand) loaded it as a working credential, at any tier.
            if not isinstance(e.token, str) or not e.token.strip():
                raise ValueError(f"{path}: caller {e.caller_id!r} has no token")
            if "REPLACE-WITH" in e.token.upper() or e.token.startswith("<"):
                raise ValueError(
                    f"{path}: caller {e.caller_id!r} still has a placeholder token. Mint "
                    f"one: python3 -c 'import secrets; print(secrets.token_urlsafe(32))'"
                )
            if len(e.token) < MIN_TOKEN_CHARS:
                logging.getLogger(__name__).warning(
                    "weak_bearer_token: caller %r has a %d-character token; mint one of "
                    "at least %d (python3 -c 'import secrets; "
                    "print(secrets.token_urlsafe(32))')", e.caller_id, len(e.token),
                    MIN_TOKEN_CHARS,
                )
        # One token, one credential. A token listed twice used to keep whichever
        # entry came last, silently; listed once as a supervisor and once with
        # the actuate tier, it would be a heartbeat that can also move the robot.
        tokens = [e.token for e in entries]
        if len(set(tokens)) != len(tokens):
            twice = sorted({e.caller_id or "?" for e in entries if tokens.count(e.token) > 1})
            raise ValueError(
                f"{path}: a token is listed more than once (callers {', '.join(twice)}); "
                f"give each credential its own token"
            )
        return cls(entries)

    def resolve(self, token: str) -> _BearerEntry | None:
        return self._by_token.get(token)


def _parse_bearer(authorization: str | None) -> str:
    if not authorization:
        raise HTTPException(status_code=401, detail="missing Authorization header")
    prefix = "Bearer "
    if not authorization.startswith(prefix):
        raise HTTPException(status_code=401, detail="Authorization must be Bearer <token>")
    return authorization.removeprefix(prefix).strip()


def _validate_api_key(key: str | None) -> str:
    if not key:
        raise HTTPException(
            status_code=401,
            detail="missing X-Anthropic-Api-Key header (BYOK required)",
        )
    if not key.startswith("sk-ant-"):
        raise HTTPException(status_code=401, detail="invalid Anthropic API key format")
    return key


def make_auth_dep(store: BearerStore):
    def dep(
        authorization: str | None = Header(default=None),
        x_anthropic_api_key: str | None = Header(default=None),
    ) -> AuthContext:
        token = _parse_bearer(authorization)
        entry = store.resolve(token)
        if entry is None:
            raise HTTPException(status_code=401, detail="unknown bearer")
        api_key = _validate_api_key(x_anthropic_api_key)
        return AuthContext(
            caller_id=entry.caller_id,
            tier=entry.tier,
            api_key=api_key,
        )

    return dep


def load_bearer_store_from_env() -> BearerStore:
    path = os.environ.get("ROBOT_MD_BEARERS_FILE")
    if not path:
        raise RuntimeError("ROBOT_MD_BEARERS_FILE not set")
    return BearerStore.from_yaml(Path(path))


def load_actuator_section(path: Path) -> dict:
    """Read the optional ``actuator:`` section of bearers.yaml.

    Returns a normalized dict with ``name`` (default ``"noop"``) and ``config``
    (default empty dict). Legacy list-shape bearers.yaml has no actuator
    section and falls back to the noop default.
    """
    data = yaml.safe_load(path.read_text())
    if not isinstance(data, dict):
        return {"name": "noop", "config": {}}
    section = data.get("actuator") or {}
    return {
        "name": section.get("name") or "noop",
        "config": section.get("config") or {},
    }


def load_actuators_section(path: Path) -> list[dict]:
    """Read the optional ``actuators:`` list-shape section of bearers.yaml.

    The list-shape registers multiple actuators behind one gateway; the
    receiver routes by `envelope.actuator_name`. Each entry is a dict with
    ``name`` (required) and ``config`` (optional). Returns ``[]`` when the
    section is absent — caller should fall back to ``load_actuator_section``.
    """
    data = yaml.safe_load(path.read_text())
    if not isinstance(data, dict):
        return []
    raw = data.get("actuators")
    if not isinstance(raw, list):
        return []
    out: list[dict] = []
    for entry in raw:
        if not isinstance(entry, dict):
            continue
        name = entry.get("name")
        if not name:
            continue
        out.append({"name": name, "config": entry.get("config") or {}})
    return out


class RRFResolverFromEnv:
    """Resolves a kid → public-key PEM via the RRF v2 API.

    Reads OPENCASTOR_OPS_RRF_URL (default https://robotregistryfoundation.org).
    Caches lookups in process memory for the gateway's lifetime; revocation
    polling is added in Plan 6 (RR-001).
    """

    def __init__(self, base_url: str) -> None:
        self._base = base_url.rstrip("/")
        self._cache: dict[str, bytes] = {}

    @classmethod
    def from_env(cls) -> RRFResolverFromEnv:
        default = "https://robotregistryfoundation.org"
        return cls(os.environ.get("OPENCASTOR_OPS_RRF_URL", default))

    def resolve_public_key_pem(self, kid: str) -> bytes | None:
        if kid in self._cache:
            return self._cache[kid]
        import json
        import urllib.request
        url = f"{self._base}/v2/keys/{kid}"
        # Cloudflare in front of robotregistryfoundation.org rejects requests
        # with the default Python-urllib/* User-Agent (HTTP 403). Send a
        # distinct, identifying UA the WAF allows. Includes the gateway version
        # so prod log analysis can correlate kid-resolution patterns with
        # gateway releases.
        try:
            from . import __version__ as _ver  # type: ignore[attr-defined]
        except Exception:
            _ver = "unknown"
        req = urllib.request.Request(
            url,
            headers={"User-Agent": f"robot-md-gateway/{_ver} (+kid-resolver)"},
        )
        try:
            with urllib.request.urlopen(req, timeout=5) as resp:
                if resp.status != 200:
                    return None
                payload = json.loads(resp.read())
                pem = payload.get("public_key_pem", "").encode("utf-8")
                if pem:
                    self._cache[kid] = pem
                return pem or None
        except Exception:
            return None
