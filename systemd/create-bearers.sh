#!/usr/bin/env bash
# Create the gateway's bearer file with two freshly generated tokens: an
# actuate-tier token for the agent's client, and a supervisor token for the
# device that sends heartbeats (it can stop the robot and read, nothing else).
# There is no commission token: clearing a stop is a deliberate act, so the
# operator adds that entry by hand, and install.sh says so. Called by
# install.sh; kept separate so it can be tested on its own.
#
# Usage: create-bearers.sh <path> <owner> <group>
#
#   - never overwrites: an existing file is left exactly as it is. The name is
#     taken with link(2), which fails if anything already has it, so a run
#     racing another cannot replace the other's file;
#   - never prints a token (read them with: sudo cat <path>);
#   - the file is 0640 and owned by <owner>:<group> before it gets its name
#     (install.sh passes root:robot: the service reads it through its group
#     and cannot rewrite its own credentials);
#   - on any failure nothing is left behind.
set -euo pipefail

if [[ $# -ne 3 ]]; then
    echo "usage: $0 <path> <owner> <group>" >&2
    exit 2
fi
path=$1
owner=$2
group=$3

if [[ -e "$path" ]]; then
    echo "bearer file exists, left unchanged: $path"
    exit 0
fi

tmp=$(mktemp "$(dirname -- "$path")/.bearers.XXXXXXXX")   # mktemp creates it 0600
trap 'rm -f -- "$tmp"' EXIT
chown "$owner:$group" "$tmp"
chmod 0640 "$tmp"

new_token() { python3 -c 'import secrets; print(secrets.token_urlsafe(32))'; }
actuate=$(new_token)
supervisor=$(new_token)
cat >"$tmp" <<EOF
# robot-md-gateway bearers, generated by install.sh. Never commit this file.
# One entry per client, so each receipt names the credential that acted
# (caller). tier: read | actuate | commission. role: supervisor marks the
# heartbeat credential. Edit with sudoedit, then restart the service. See
# README.md, "Bearer tokens" and "Heartbeat and safe-stop".
bearers:
  # The agent's client. It can move the robot; it cannot clear a stop.
  - token: "$actuate"
    tier: actuate
    caller: actuate-default
  # The heartbeat sender: the supervising person's device, never the agent's
  # host and never the robot. It can stop the robot and read; nothing else.
  - token: "$supervisor"
    role: supervisor
    caller: supervisor-default
  # The gateway starts held, and only a commission clear arms it. Add the
  # operator's entry by hand, with a token of its own:
  #   python3 -c 'import secrets; print(secrets.token_urlsafe(32))'
  # - token: "<that token>"
  #   tier: commission
  #   caller: <the operator>
EOF

if ! ln -- "$tmp" "$path" 2>/dev/null; then
    if [[ -e "$path" ]]; then
        echo "bearer file exists, left unchanged: $path"
        exit 0
    fi
    echo "could not create $path" >&2
    exit 1
fi
rm -f -- "$tmp"
trap - EXIT
echo "created $path (mode 0640, $owner:$group) with an actuate-tier token and a" \
     "supervisor token, and no commission entry; read it with: sudo cat $path"
