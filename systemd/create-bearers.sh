#!/usr/bin/env bash
# Create the gateway's bearer file, holding one freshly generated actuate-tier
# token. Called by install.sh; kept separate so it can be tested on its own.
#
# Usage: create-bearers.sh <path> <owner> <group>
#
#   - never overwrites: an existing file is left exactly as it is;
#   - never prints the token (read it with: sudo cat <path>);
#   - the file is 0600 and owned by <owner>:<group> before it gets its name,
#     so there is no moment when the token is readable by anyone else;
#   - on any failure nothing is left behind.
set -euo pipefail

if [[ $# -ne 3 ]]; then
    echo "usage: $0 <path> <owner> <group>" >&2
    exit 2
fi
path=$1
owner=$2
group=$3

if [[ -e "$path" ]]; then
    echo "bearer file exists, left unchanged: $path"
    exit 0
fi

tmp=$(mktemp "$(dirname -- "$path")/.bearers.XXXXXXXX")   # mktemp creates it 0600
trap 'rm -f -- "$tmp"' EXIT
chown "$owner:$group" "$tmp"
chmod 0600 "$tmp"

token=$(python3 -c 'import secrets; print(secrets.token_urlsafe(32))')
cat >"$tmp" <<EOF
# robot-md-gateway bearers, generated by install.sh. Never commit this file.
# One entry per client, so each receipt names the credential that acted
# (caller). tier: read | actuate | commission. Edit with sudoedit, then
# restart the service. See README.md, "Bearer tokens".
bearers:
  - token: "$token"
    tier: actuate
    caller: actuate-default
EOF

mv -- "$tmp" "$path"
trap - EXIT
echo "created $path (mode 0600, owner $owner) with one actuate-tier token; read it with: sudo cat $path"
